import {expect,test} from '@playwright/test';
import {captureBrowserErrors,mockRoasApi} from './fixtures';

test('registra foco e descanso pelo modal e flutuante, sem apagar ao encerrar',async({page})=>{
 const errors=captureBrowserErrors(page);
 await page.clock.install({time:new Date('2026-11-24T12:00:00Z')});
 await mockRoasApi(page);await page.goto('/tasks?task=task-future');
 const dialog=page.getByRole('dialog');
 await dialog.getByRole('button',{name:'Ativar · 25 min'}).click();
 await page.clock.fastForward(60000);
 await dialog.getByRole('button',{name:'Pausar sessão'}).click();
 const stats=dialog.locator('.pomodoroTimeStats');
 await expect(stats).toContainText('1min 0s');
 await page.clock.fastForward(120000);
 await expect(stats).toContainText('1min 0s');
 await dialog.getByRole('button',{name:'Retomar foco'}).click();
 await dialog.getByRole('button',{name:'Cancelar',exact:true}).click();
 const floating=page.getByRole('complementary',{name:'Pomodoro flutuante'});
 await page.clock.fastForward(1440000);
 await expect(floating).toContainText('Foco concluído');
 await floating.getByRole('button',{name:'Iniciar pausa'}).click();
 await page.clock.fastForward(120000);
 await floating.getByRole('button',{name:'Pausar',exact:true}).click();
 await floating.getByRole('link',{name:'Abrir tarefa'}).click();
 await expect(stats).toContainText('25min 0s');
 await expect(stats).toContainText('2min 0s');
 await expect(stats.locator('b').nth(2)).toHaveText('1');
 await dialog.getByRole('button',{name:'Encerrar e reiniciar Pomodoro'}).click();
 await expect(stats).toContainText('25min 0s');
 await dialog.getByRole('button',{name:'Salvar tarefa',exact:true}).click();
 await page.clock.runFor(1000);
 await page.reload();
 await page.goto('/tasks?task=task-future');
 await expect(stats).toContainText('25min 0s');
 await expect(stats).toContainText('2min 0s');
 expect(errors).toEqual([]);
});

test('trocar tarefa pausa a anterior e encerrar um foco parcial preserva o tempo',async({page})=>{
 await page.clock.install({time:new Date('2026-11-24T12:00:00Z')});
 await mockRoasApi(page);await page.goto('/tasks?task=task-future');
 const dialog=page.getByRole('dialog');
 await dialog.getByRole('button',{name:'Ativar · 25 min'}).click();
 await page.clock.fastForward(90000);
 await dialog.getByRole('button',{name:'Cancelar',exact:true}).click();
 await page.goto('/tasks?task=task-overdue');
 await dialog.getByRole('button',{name:'Ativar · 25 min'}).click();
 await page.clock.fastForward(60000);
 await dialog.getByRole('button',{name:'Encerrar e reiniciar Pomodoro'}).click();
 await expect(dialog.locator('.pomodoroTimeStats b').nth(0)).toHaveText('1min 0s');
 await expect(dialog.locator('.pomodoroTimeStats b').nth(2)).toHaveText('0');
 await dialog.getByRole('button',{name:'Cancelar',exact:true}).click();
 await page.goto('/tasks?task=task-future');
 await expect(dialog).toContainText('Sessão pausada');
 await expect(dialog.locator('.pomodoroTimeStats b').nth(0)).toHaveText(/1min 3[0-9]s/);
 const pausedTime=await dialog.locator('.pomodoroTimeStats b').nth(0).textContent();
 await page.clock.fastForward(60000);
 await expect(dialog.locator('.pomodoroTimeStats b').nth(0)).toHaveText(pausedTime!);
 await dialog.locator('.pomodoroHistory summary').click();
 await expect(dialog.locator('.pomodoroHistory tbody')).toContainText('Admin E2E');
 await expect(dialog.locator('.pomodoroHistory tbody')).toContainText('Parcial');
});
